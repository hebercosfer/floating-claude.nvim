local config = require("floating-claude.config")

describe("config", function()
  after_each(function()
    config.setup({})
  end)

  it("starts from the defaults without setup()", function()
    assert.equals(config.defaults.float.width, config.options.float.width)
    assert.is_true(config.options.version_check)
  end)

  it("merges deeply, keeping untouched keys", function()
    config.setup({ float = { width = 0.5 } })
    assert.equals(0.5, config.options.float.width)
    assert.equals(config.defaults.float.height, config.options.float.height)
    assert.equals(config.defaults.notification.width, config.options.notification.width)
  end)

  it("tolerates setup() with no arguments", function()
    config.setup()
    assert.same(config.defaults, config.options)
  end)

  it("does not accumulate across calls", function()
    config.setup({ notification = { width = 20 } })
    config.setup({ notification = { max_height = 3 } })
    assert.equals(config.defaults.notification.width, config.options.notification.width)
    assert.equals(3, config.options.notification.max_height)
  end)

  it("never mutates the defaults", function()
    local before = vim.deepcopy(config.defaults)
    config.setup({ float = { border = "single" }, keymaps = { minimize = false } })
    assert.same(before, config.defaults)
  end)

  it("accepts version_check = false", function()
    config.setup({ version_check = false })
    assert.is_false(config.options.version_check)
  end)

  describe("inline mode", function()
    it("defaults to the session, waiting for Claude, and the three virtual lines", function()
      local inline = config.setup({}).inline
      assert.is_true(inline.enabled)
      assert.equals("session", inline.mode)
      assert.equals("wait", inline.when_busy)
      assert.equals(3, inline.lines)
      assert.equals(6, inline.max_input_height)
      assert.equals("unified", inline.diff_layout)
      assert.is_true(inline.diff_in_window)
    end)

    it("defaults the headless process to claude, reviewing what it proposes", function()
      local headless = config.setup({}).inline.headless
      assert.same({ "claude" }, headless.cmd)
      assert.is_false(headless.model)
      assert.equals("review", headless.apply)
      assert.equals(40, headless.context_lines)
    end)

    it("puts the key on <leader>ai", function()
      assert.equals("<leader>ai", config.setup({}).keymaps.inline)
    end)

    it("merges over the defaults, key by key", function()
      config.setup({ inline = { lines = 5, headless = { apply = "stream" } } })
      assert.equals(5, config.options.inline.lines)
      assert.equals("stream", config.options.inline.headless.apply)
      assert.equals(40, config.options.inline.headless.context_lines)
      assert.equals("wait", config.options.inline.when_busy)
    end)
  end)

  describe("reading Claude through hooks", function()
    it("defaults hooks on, keeping 50 events", function()
      config.setup({})
      assert.same({ enabled = true, keep = 50 }, config.options.hooks)
    end)

    it("accepts hooks = false", function()
      config.setup({ hooks = false })
      assert.same({ enabled = false, keep = 50 }, config.options.hooks)
    end)

    it("accepts a table that keeps none", function()
      config.setup({ hooks = { keep = 0 } })
      assert.same({ enabled = true, keep = 0 }, config.options.hooks)
    end)

    it("reads restore_on_input = true as idle", function()
      config.setup({ auto = { restore_on_input = true } })
      assert.equals("idle", config.options.auto.restore_on_input)
    end)

    it("defaults the corner's content to activity", function()
      config.setup({})
      assert.equals("activity", config.options.notification.content)
    end)

    it("defaults show_hidden to request and the events key to <leader>ae", function()
      config.setup({})
      assert.equals("request", config.options.auto.show_hidden)
      assert.equals("<leader>ae", config.options.keymaps.events)
    end)
  end)
end)
